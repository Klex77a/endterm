import io, json, sys, contextlib, html, time
sys.path.insert(0, ".")
from labs_src import LABS
out = {}
for week, labs in LABS.items():
    out[week] = []
    for title, intro, code in labs:
        code = code.strip("\n")
        buf = io.StringIO(); t = time.time()
        with contextlib.redirect_stdout(buf):
            exec(compile(code, title, "exec"), {"__name__": "__main__"})
        out[week].append({"title": title, "intro": intro, "code": code, "output": buf.getvalue().rstrip()})
        print(f"W{week} {title}: {time.time()-t:.2f}s", file=sys.stderr)
js = ("/* Python labs — generated by build_labs.py. Every output below was produced by\n"
      "   actually running the code (Python 3, NumPy, scikit-learn). */\n"
      "window.BOOK = window.BOOK || { chapters: [] };\nwindow.BOOK.labs = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
open("../js/labs.js", "w").write(js)
for w in out:
    for l in out[w]:
        print(f"===== W{w} {l['title']}\n{l['output']}")
